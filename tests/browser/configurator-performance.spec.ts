import { selectAssemblySlot } from "./helpers/assembly";
import { test, expect } from "@playwright/test";
import { installSceneMetrics } from "../../scripts/lib/scene-metrics.mjs";
test.use({ launchOptions: { args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] } });

test("configurator batches search, reuses categories and warms only the intended GLB", async ({ page }) => {
  test.skip(!process.env.ATLAS_TEST_EMAIL, "Run through scripts/validate-configurator-performance.mjs");
  test.setTimeout(90000);
  await page.addInitScript(installSceneMetrics);
  const queries: URL[] = [];
  const assets: string[] = [];
  page.on("request", request => {
    const url = new URL(request.url());
    if (url.pathname.endsWith("/rest/v1/components")) queries.push(url);
    if (url.pathname.includes("/storage/v1/object/public/models/")) assets.push(url.pathname);
  });
  await page.goto("/entrar");
  await page.getByLabel("Correo electrónico").fill(process.env.ATLAS_TEST_EMAIL!);
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.ATLAS_TEST_PASSWORD!);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/mis-bicicletas/);
  await page.goto("/configurador");
  const firstFrame = page.locator(".piece-options > button").first();
  await expect(firstFrame).toBeVisible();
  expect(assets).toHaveLength(0);
  const assetResponse = page.waitForResponse(response => response.url().includes("/storage/v1/object/public/models/"));
  await firstFrame.hover();
  const response = await assetResponse;
  expect(response.ok()).toBe(true);
  await response.finished();
  const downloadsAfterIntent = assets.length;
  const queriesBeforeApply = queries.length;
  const browserStart = await page.evaluate(() => performance.now());
  const start = performance.now();
  await firstFrame.click();
  await expect(page.locator(".save-status")).toContainText("Pieza aplicada");
  const applyMs = Math.round(performance.now() - start);
  expect(assets).toHaveLength(downloadsAfterIntent);
  const downloadsOnApply = assets.length - downloadsAfterIntent;
  expect(queries).toHaveLength(queriesBeforeApply);
  await expect(page.locator(".viewer canvas")).toBeVisible();
  await page.waitForFunction(() => (window as any).atlasSceneProof?.firstDrawMs != null);
  const firstDrawMs = Math.round(await page.evaluate(() => (window as any).atlasSceneProof.firstDrawMs) - browserStart);
  await selectAssemblySlot(page, "Horquilla");
  await expect(page.locator(".piece-options > button").first()).toBeVisible();
  const beforeTyping = queries.length;
  await page.getByLabel("Buscar alternativa").pressSequentially("Fac", { delay: 35 });
  await expect.poll(() => queries.length - beforeTyping).toBe(1);
  await expect(page.locator(".piece-options > button").first()).toBeVisible();
  const beforeSwitch = queries.length;
  await selectAssemblySlot(page, "Amortiguador");
  await expect(page.locator(".piece-options > button").first()).toBeVisible();
  const switched = queries.slice(beforeSwitch);
  expect(switched).toHaveLength(1);
  expect(switched[0].searchParams.get("name")).toBeNull();
  const beforeReturn = queries.length;
  await selectAssemblySlot(page, "Horquilla");
  await expect(page.getByLabel("Buscar alternativa")).toHaveValue("");
  await expect(page.locator(".piece-options > button").first()).toBeVisible();
  expect(queries).toHaveLength(beforeReturn);
  await expect(page.getByText("Vista 3D no disponible", { exact: true })).toHaveCount(0);
  console.log(JSON.stringify({ scope: "configurator", applyAfterIntentMs: applyMs, firstDrawAfterIntentMs: firstDrawMs, modelDownloadsOnApply: downloadsOnApply, databaseQueriesOnApply: 0, searchQueriesForThreeKeys: 1, cachedCategoryQueries: queries.length - beforeReturn }));
});

test("saved builds reuse their confirmed snapshot across details, tabs and editor", async ({ page }) => {
  test.skip(!process.env.ATLAS_TEST_EMAIL, "Run through scripts/validate-configurator-performance.mjs");
  test.setTimeout(90000);
  const reads: string[] = [];
  page.on("request", request => {
    if (new URL(request.url()).pathname.endsWith("/rest/v1/builds") && request.method() === "GET") reads.push(request.url());
  });
  await page.goto("/entrar");
  await page.getByLabel("Correo electrónico").fill(process.env.ATLAS_TEST_EMAIL!);
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.ATLAS_TEST_PASSWORD!);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/mis-bicicletas/);
  await page.goto("/configurador");
  const firstFrame = page.locator(".piece-options > button").first();
  await expect(firstFrame).toBeVisible();
  await firstFrame.click();
  await expect(page.locator(".save-status")).toContainText("Pieza aplicada");
  const name = `Saved cache ${Date.now()}`;
  await page.getByLabel("Nombre del montaje").fill(name);
  await page.getByRole("button", { name: "Guardar", exact: true }).click();
  await expect(page.locator(".save-status")).toHaveText("Guardado");
  await page.locator(".editor-toolbar").getByRole("link", { name: "Mis bicicletas", exact: true }).click();
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
  const card = page.locator(".preset-card").filter({ hasText: name });
  await expect(card.locator(".bike-preview")).toHaveAttribute("data-preview-state", "ready");
  await expect.poll(() => card.locator(".bike-preview-image").evaluate((image: HTMLImageElement) => image.naturalWidth)).toBe(640);
  await expect(card.locator("canvas")).toHaveCount(0);
  await expect(card.getByText("1 pieza", { exact: true })).toBeVisible();
  await expect(page.locator("[data-bike-preview-renderer]")).toHaveCount(0);
  const beforeDetails = reads.length;
  await page.getByRole("button", { name, exact: true }).click();
  await expect(page.getByRole("dialog").getByLabel("Nombre", { exact: true })).toHaveValue(name);
  await page.getByRole("button", { name: "Cerrar detalle" }).click();
  await page.getByRole("button", { name, exact: true }).click();
  await expect(page.getByRole("dialog").getByLabel("Nombre", { exact: true })).toHaveValue(name);
  await page.getByRole("button", { name: "Cerrar detalle" }).click();
  expect(reads).toHaveLength(beforeDetails);
  await page.locator(".workspace-tabs").getByRole("link", { name: "Componentes", exact: true }).click();
  await expect(page).toHaveURL(/componentes/);
  await page.locator(".workspace-tabs").getByRole("link", { name: "Mis bicicletas", exact: true }).click();
  await expect(page.getByRole("button", { name, exact: true })).toBeVisible();
  expect(reads).toHaveLength(beforeDetails);
  await page.getByRole("link", { name: "Continuar", exact: false }).first().click();
  await expect(page.getByLabel("Nombre del montaje")).toHaveValue(name);
  expect(reads).toHaveLength(beforeDetails);
  console.log(JSON.stringify({ scope: "garage", detailReopenReads: 0, cachedTabReturnReads: 0, editorReopenReads: 0 }));
});

test("a complete preset reuses gallery items and loaded models when reopened", async ({ page }) => {
  test.skip(!process.env.ATLAS_TEST_EMAIL, "Run through scripts/validate-configurator-performance.mjs");
  test.setTimeout(90000);
  const presets: string[] = [], assets: string[] = [];
  page.on("request", request => {
    const url = new URL(request.url());
    if (url.pathname.endsWith("/rest/v1/bike_presets")) presets.push(url.href);
    if (url.pathname.includes("/storage/v1/object/public/models/")) assets.push(url.pathname);
  });
  await page.goto("/entrar");
  await page.getByLabel("Correo electrónico").fill(process.env.ATLAS_TEST_EMAIL!);
  await page.getByLabel("Contraseña", { exact: true }).fill(process.env.ATLAS_TEST_PASSWORD!);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/mis-bicicletas/);
  await page.locator(".workspace-tabs").getByRole("link", { name: "Bicicletas", exact: true }).click();
  await expect(page.locator(".bicycle-card .bike-preview").first()).toHaveAttribute("data-preview-state", "ready");
  const firstPreset = page.locator(".bicycle-card").first().getByRole("link", { name: "Personalizar", exact: false });
  const beforeOpen = presets.length;
  await firstPreset.click();
  await expect(page.locator(".viewer canvas")).toBeVisible();
  await expect(page.locator(".slot-complete")).toHaveCount(23);
  expect(presets).toHaveLength(beforeOpen);
  await page.locator(".workspace-tabs").getByRole("link", { name: "Bicicletas", exact: true }).click();
  await page.getByRole("button", { name: "Descartar y salir", exact: true }).click();
  await expect(page.locator(".bicycle-card").first()).toBeVisible();
  const beforeReopen = { presets: presets.length, assets: assets.length };
  await firstPreset.click();
  await expect(page.locator(".viewer canvas")).toBeVisible();
  await expect(page.locator(".slot-complete")).toHaveCount(23);
  expect(presets).toHaveLength(beforeReopen.presets);
  expect(assets).toHaveLength(beforeReopen.assets);
  await expect(page.getByText("Vista 3D no disponible", { exact: true })).toHaveCount(0);
  console.log(JSON.stringify({ scope: "complete-preset", slots: 23, presetReadsOnOpen: 0, presetReadsOnReopen: 0, modelDownloadsOnReopen: 0 }));
});
